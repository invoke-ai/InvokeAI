/** The starts the widget sends index-clipping denoise nodes, recorded for the backend to replay. */

import type { MainModelConfig } from '@features/generation/contracts';

import { describe, expect, it } from 'vitest';

import type { UpscaleBase } from './settings';

import { getIndexClippedDenoisingStart, getUpscaleDenoisingStart } from './graph';
import { UPSCALE_ARCHITECTURES } from './settings';

const CREATIVITIES = [-10, -5, 0, 5, 8, 10];
const STEP_COUNTS = [8, 30];
// Z-Image's shift follows the frame up to one megapixel and Krea-2 Raw's up to 1280x1280, held above;
// Anima's and Krea-2 Turbo's are fixed.
const MODELS: readonly { base: UpscaleBase; variant: string | null; sides: readonly number[] }[] = [
  { base: 'anima', sides: [1024], variant: null },
  { base: 'krea-2', sides: [1024], variant: 'krea2_turbo' },
  { base: 'krea-2', sides: [512, 1024, 2048, 4096], variant: 'krea2_base' },
  { base: 'z-image', sides: [512, 1024, 2048, 4096], variant: null },
];
const BASES = [...new Set(MODELS.map((model) => model.base))];

describe('index-clipped denoising starts', () => {
  it('covers every architecture whose denoise node clips by index', () => {
    const indexClipped = Object.entries(UPSCALE_ARCHITECTURES)
      .filter(([, architecture]) => architecture.indexClipping)
      .map(([base]) => base);

    expect([...BASES].sort()).toEqual(indexClipped.sort());
  });

  it('records what the widget sends, so the backend can check it against its real schedules', async () => {
    const cases = MODELS.flatMap(({ base, sides, variant }) =>
      sides.flatMap((side) =>
        STEP_COUNTS.flatMap((steps) =>
          CREATIVITIES.map((creativity) => {
            const valueStart = getUpscaleDenoisingStart(creativity);
            const clipping = UPSCALE_ARCHITECTURES[base].indexClipping!;
            const model = { base, variant } as MainModelConfig;
            const shift = clipping.shift(model, { height: side, width: side });

            return {
              base,
              creativity,
              denoisingStart: getIndexClippedDenoisingStart(valueStart, steps, shift, clipping.rounding),
              fluxEntrySigma: 1 - valueStart,
              side,
              steps,
              variant,
            };
          })
        )
      )
    );
    const fixture = {
      _comment:
        'Generated by src/features/upscale/core/indexClippedStarts.test.ts; regenerate with `vitest -u`. ' +
        'Consumed by tests/app/invocations/test_upscale_index_clipped_starts.py, which drives the real ' +
        'z_image_denoise, anima_denoise and krea2_denoise with each denoisingStart and checks the pass ' +
        'enters at the step nearest fluxEntrySigma, and that the schedulers offered are the ones that ' +
        'start there.',
      cases,
      schedulers: Object.fromEntries(BASES.map((base) => [base, UPSCALE_ARCHITECTURES[base].schedulers])),
    };

    await expect(`${JSON.stringify(fixture, null, 2)}\n`).toMatchFileSnapshot(
      './__snapshots__/upscaleIndexClippedStarts.json'
    );
  });
});

/** The starts the widget sends index-clipping denoise nodes, recorded for the backend to replay. */

import { describe, expect, it } from 'vitest';

import type { UpscaleBase } from './settings';

import { getIndexClippedDenoisingStart, getUpscaleDenoisingStart } from './denoisingStart';
import { UPSCALE_ARCHITECTURES } from './settings';

const CREATIVITIES = [-10, -5, 0, 5, 8, 10];
const STEP_COUNTS = [8, 30];
// Z-Image's shift follows the frame up to one megapixel; Anima's is fixed.
const FRAME_SIDES: Partial<Record<UpscaleBase, number[]>> = { anima: [1024], 'z-image': [512, 1024, 2048, 4096] };

describe('index-clipped denoising starts', () => {
  it('covers every architecture whose denoise node clips by index', () => {
    const indexClipped = Object.entries(UPSCALE_ARCHITECTURES)
      .filter(([, architecture]) => architecture.indexClippedShift)
      .map(([base]) => base);

    expect(Object.keys(FRAME_SIDES).sort()).toEqual(indexClipped.sort());
  });

  it('records what the widget sends, so the backend can check it against its real schedules', async () => {
    const cases = Object.entries(FRAME_SIDES).flatMap(([base, sides]) =>
      sides.flatMap((side) =>
        STEP_COUNTS.flatMap((steps) =>
          CREATIVITIES.map((creativity) => {
            const valueStart = getUpscaleDenoisingStart(creativity);
            const shift = UPSCALE_ARCHITECTURES[base as UpscaleBase].indexClippedShift!({ height: side, width: side });

            return {
              base,
              creativity,
              denoisingStart: getIndexClippedDenoisingStart(valueStart, steps, shift),
              fluxEntrySigma: 1 - valueStart,
              side,
              steps,
            };
          })
        )
      )
    );
    const fixture = {
      _comment:
        'Generated by src/features/upscale/core/denoisingStart.test.ts; regenerate with `vitest -u`. ' +
        'Consumed by tests/app/invocations/test_upscale_index_clipped_starts.py, which drives the real ' +
        'z_image_denoise and anima_denoise with each denoisingStart and checks the pass enters at the ' +
        'step nearest fluxEntrySigma.',
      cases,
    };

    await expect(`${JSON.stringify(fixture, null, 2)}\n`).toMatchFileSnapshot(
      './__snapshots__/upscaleIndexClippedStarts.json'
    );
  });
});

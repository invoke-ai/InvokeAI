import type { SVGProps } from 'react';

/**
 * Vendored paths avoid large icon barrels. Simple Icons paths are CC0-1.0 (https://simpleicons.org); other glyph
 * sources are recorded in origin. Preserve upstream slug/title and viewBox for updates.
 */

interface VendoredIconSource {
  /** Upstream slug, for refreshing the path later. */
  slug: string;
  /** Upstream title, used as the accessible name when the icon is not decorative. */
  title: string;
  /** The `path` `d` attributes, drawn in order. */
  paths: readonly string[];
  /** The source's viewBox; Simple Icons draw on 24×24. */
  viewBox?: string;
  /** Where the icon came from, when it is not Simple Icons. */
  origin?: string;
}

const createVendoredIcon = ({ paths, title, viewBox = '0 0 24 24' }: VendoredIconSource) => {
  const VendoredIcon = ({ titleAccess, ...props }: SVGProps<SVGSVGElement> & { titleAccess?: boolean }) => (
    <svg
      // Decorative by default to avoid duplicate announcements; pass titleAccess for standalone icons.
      aria-hidden={titleAccess ? undefined : true}
      fill="currentColor"
      height="1em"
      role={titleAccess ? 'img' : undefined}
      viewBox={viewBox}
      width="1em"
      xmlns="http://www.w3.org/2000/svg"
      {...props}
    >
      {titleAccess ? <title>{title}</title> : null}
      {paths.map((path) => (
        <path key={path} d={path} />
      ))}
    </svg>
  );

  VendoredIcon.displayName = `VendoredIcon(${title})`;

  return VendoredIcon;
};


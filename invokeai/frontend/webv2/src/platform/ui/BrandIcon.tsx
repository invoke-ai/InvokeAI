import type { SVGProps } from 'react';

/**
 * Brand marks, vendored from Simple Icons (https://simpleicons.org, CC0-1.0).
 *
 * Everything non-brand is a Lucide icon; brands are the only exception, and
 * there are a handful of them. Both `react-icons/si` and the `simple-icons`
 * package expose their icons through a single ~5 MB barrel module with no
 * per-icon entry point, which the dev server transforms in full to hand back
 * four paths — so the paths live here instead, as the data they are.
 *
 * To add or refresh one: copy the 24×24 path from simpleicons.org (or
 * `npx -y simple-icons@latest`), keeping the slug and title as the upstream
 * name so a later refresh is a straight lookup.
 */

interface BrandIconSource {
  /** Upstream Simple Icons slug, for refreshing the path later. */
  slug: string;
  /** Upstream title, used as the accessible name when the icon is not decorative. */
  title: string;
  /** The 24×24 `path` `d` attribute. */
  path: string;
}

const createBrandIcon = ({ path, title }: BrandIconSource) => {
  const BrandIcon = ({ titleAccess, ...props }: SVGProps<SVGSVGElement> & { titleAccess?: boolean }) => (
    <svg
      // Decorative by default: every current consumer pairs the mark with
      // visible text, and a titled icon there is announced twice. Pass
      // `titleAccess` when the icon stands alone.
      aria-hidden={titleAccess ? undefined : true}
      fill="currentColor"
      height="1em"
      role={titleAccess ? 'img' : undefined}
      viewBox="0 0 24 24"
      width="1em"
      xmlns="http://www.w3.org/2000/svg"
      {...props}
    >
      {titleAccess ? <title>{title}</title> : null}
      <path d={path} />
    </svg>
  );

  BrandIcon.displayName = `BrandIcon(${title})`;

  return BrandIcon;
};


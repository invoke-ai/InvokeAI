FIXTURE_PATH = (
    Path(__file__).parents[3]
    / "invokeai/frontend/webv2/src/features/generation/core/__snapshots__/externalCanvasGraphs.json"
)
GRAPHS: dict[str, Any] = {
    name: graph for name, graph in json.loads(FIXTURE_PATH.read_text(encoding="utf-8")).items() if name != "_comment"
}


# The Canvas bbox is 640x512; GPT Image 1's size table answers its 5:4 frame with the 3:2 size 1536x1024.
BBOX = (640, 512)
PROVIDER_SIZE = (1536, 1024)


def _sources(graph: Graph) -> dict[tuple[str, str], EdgeConnection]:
    return {(edge.destination.node_id, edge.destination.field): edge.source for edge in graph.edges}


@pytest.mark.parametrize("mode", ["txt2img", "img2img"])
def test_hosted_canvas_graph_is_valid_for_the_backend(mode: str) -> None:
    graph = Graph.model_validate(GRAPHS[mode])
    graph.validate_self()
    for node_id, raw in GRAPHS[mode]["nodes"].items():
        node = graph.nodes[node_id]
        unknown = set(raw) - set(type(node).model_fields)
        if type(node).model_config.get("extra") == "allow":
            # Core metadata intentionally preserves provider-specific fields beyond its declared schema.
            assert {key: node.model_dump()[key] for key in unknown} == {key: raw[key] for key in unknown}
        else:
            assert not unknown, f"{raw['type']} has no field(s) {sorted(unknown)}"

    provider = graph.nodes["canvas_processing_output"]
    assert provider.mode == mode
    assert provider.num_images == 1
    assert provider.is_intermediate
    # The provider is asked for a size from its own table, so the backend has nothing to re-bucket.
    assert (provider.width, provider.height) == PROVIDER_SIZE


def test_text_to_image_covers_then_center_crops_the_provider_image_to_the_bbox() -> None:
    graph = Graph.model_validate(GRAPHS["txt2img"])
    sources = _sources(graph)
    assert graph.nodes["canvas_processing_output"].init_image is None
    assert ("canvas_processing_output", "init_image") not in sources

    output = graph.nodes["canvas_output"]
    assert output.get_type() == "img_crop"
    assert (output.width, output.height) == BBOX
    cover = graph.nodes[sources[("canvas_output", "image")].node_id]
    assert cover.get_type() == "img_resize"
    # 1536x1024 scaled by max(640/1536, 512/1024) = 0.5 covers the bbox; the 128 px overflow is split evenly.
    assert (cover.width, cover.height) == (768, 512)
    assert (output.x, output.y) == (64, 0)
    assert sources[(cover.id, "image")] == EdgeConnection(node_id="canvas_provider_image", field="item")


def test_image_to_image_sends_the_composite_at_the_request_size_and_resizes_the_result_to_the_bbox() -> None:
    graph = Graph.model_validate(GRAPHS["img2img"])
    sources = _sources(graph)
    assert graph.nodes["canvas_processing_output"].init_image is None
    request_image = graph.nodes[sources[("canvas_processing_output", "init_image")].node_id]
    assert request_image.get_type() == "img_resize"
    assert (request_image.width, request_image.height) == PROVIDER_SIZE
    assert request_image.image is not None and request_image.image.image_name == "canvas-composite.png"

    output = graph.nodes["canvas_output"]
    assert output.get_type() == "img_resize"
    assert (output.width, output.height) == BBOX
    assert sources[("canvas_output", "image")] == EdgeConnection(node_id="canvas_provider_image", field="item")


@pytest.mark.parametrize("mode", ["txt2img", "img2img"])
def test_canvas_output_retains_the_provider_output_metadata(mode: str) -> None:
    graph = Graph.model_validate(GRAPHS[mode])
    sources = _sources(graph)
    metadata_reader = graph.nodes[sources[("canvas_output", "metadata")].node_id]
    assert metadata_reader.get_type() == "metadata_from_image"
    # The reader and the output's image chain both start at the same iterate item, which pairs them per image.
    image_source = sources[("canvas_output", "image")]
    while image_source.field != "item":
        image_source = sources[(image_source.node_id, "image")]
    assert sources[(metadata_reader.id, "image")] == image_source
    assert graph.nodes[image_source.node_id].get_type() == "iterate"
    # Core dimensions enter the provider, which adds its authoritative request identity, seed and options.
    provider_metadata = graph.nodes[sources[("canvas_processing_output", "metadata")].node_id]
    assert provider_metadata.get_type() == "core_metadata"
    assert (provider_metadata.width, provider_metadata.height) == BBOX


PROVIDER_COLORS = [(200, 30, 30), (30, 200, 30)]


class _FakeOpenAIProvider(ExternalProvider):
    """Stands in for the network call: one solid-colored image per requested image, each with its own seed."""

    provider_id = "openai"

    def __init__(self, app_config: InvokeAIAppConfig, logger: logging.Logger) -> None:
        super().__init__(app_config, logger)
        self.requests: list[ExternalGenerationRequest] = []

    def is_configured(self) -> bool:
        return True

    def generate(self, request: ExternalGenerationRequest) -> ExternalGenerationResult:
        self.requests.append(request)
        return ExternalGenerationResult(
            images=[
                ExternalGeneratedImage(image=Image.new("RGB", PROVIDER_SIZE, PROVIDER_COLORS[index]), seed=1000 + index)
                for index in range(request.num_images)
            ],
            provider_request_id="req-canvas",
            provider_metadata={"revised_prompt": "canvas"},
        )


@pytest.mark.parametrize("num_images", [1, 2])
def test_each_provider_image_reaches_the_canvas_at_bbox_size_with_its_own_metadata(
    num_images: int, mock_invoker: Invoker, mock_sqlite_database: Database, tmp_path: Path
) -> None:
    services = mock_invoker.services
    services.image_files = DiskImageFileStorage(tmp_path / "images")
    services.names = SimpleNameService()
    services.urls = LocalUrlService()
    provider = _FakeOpenAIProvider(services.configuration, logging.getLogger())
    services.external_generation = ExternalGenerationService({"openai": provider}, logging.getLogger())
    services.image_files.start(mock_invoker)
    services.images.start(mock_invoker)

    raw_graph = GRAPHS["txt2img"]
    raw_model = raw_graph["nodes"]["canvas_processing_output"]["model"]
    store = ModelRecordServiceSQL(mock_sqlite_database, logging.getLogger())
    store.add_model(
        ExternalApiModelConfig(
            key=raw_model["key"],
            name=raw_model["name"],
            provider_id=raw_model["provider_id"],
            provider_model_id=raw_model["provider_model_id"],
            capabilities=ExternalModelCapabilities.model_validate(raw_model["capabilities"]),
        )
    )
    services.model_manager = SimpleNamespace(store=store)  # type: ignore[assignment]

    raw_nodes = {**raw_graph["nodes"]}
    raw_nodes["canvas_processing_output"] = {**raw_nodes["canvas_processing_output"], "num_images": num_images}
    session = GraphExecutionState(graph=Graph.model_validate({**raw_graph, "nodes": raw_nodes}))
    queue_item = SessionQueueItem(
        item_id=1,
        batch_id="batch-1",
        session_id=session.id,
        created_at="2026-01-01T00:00:00",
        updated_at="2026-01-01T00:00:00",
        started_at=None,
        completed_at=None,
        queue_id="default",
        session=session,
    )

    executed_sources: list[str] = []
    while (invocation := session.next()) is not None:
        source_id = session.prepared_source_mapping[invocation.id]
        context = build_invocation_context(
            services=services,
            data=InvocationContextData(queue_item=queue_item, invocation=invocation, source_invocation_id=source_id),
            is_canceled=lambda: False,
        )
        session.complete(invocation.id, invocation.invoke(context))
        executed_sources.append(source_id)

    assert not session.has_error()
    assert [(request.width, request.height) for request in provider.requests] == [PROVIDER_SIZE]
    # One provider request, then the iterate expands every node downstream of it once per returned image.
    assert executed_sources.count("canvas_processing_output") == 1
    assert executed_sources.count("canvas_provider_image") == num_images
    assert executed_sources.count("canvas_provider_metadata") == num_images

    outputs = [
        session.results[node_id]
        for node_id, source_id in session.prepared_source_mapping.items()
        if source_id == "canvas_output"
    ]
    assert len(outputs) == num_images
    seeds_by_color = {color: 1000 + index for index, color in enumerate(PROVIDER_COLORS[:num_images])}
    output_seeds = []
    for output in outputs:
        assert isinstance(output, ImageOutput)
        assert (output.width, output.height) == BBOX
        image = services.images.get_pil_image(output.image.image_name).convert("RGB")
        assert image.size == BBOX
        metadata = services.images.get_metadata(output.image.image_name)
        assert metadata is not None
        # The metadata travels with the image it was read from: its seed names the provider image of these pixels.
        assert metadata.root["external_seed"] == seeds_by_color[image.getpixel((320, 256))]
        assert metadata.root["external_request_id"] == "req-canvas"
        assert metadata.root["external_provider_metadata"] == {"revised_prompt": "canvas"}
        output_seeds.append(metadata.root["external_seed"])
    assert sorted(output_seeds) == sorted(seeds_by_color.values())

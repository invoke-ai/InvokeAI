"""Validate the frontend's hosted Canvas graphs against the real invocation fields and edge types, and run them.

The fixture is generated by compileCanvasGraph.test.ts. Graph.validate_self checks the collection-to-item conversion
and the image/metadata inputs of the output nodes. The execution test runs a graph through GraphExecutionState with
real image storage and a fake provider in place of the network call.
"""

